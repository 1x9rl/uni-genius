CREATE TABLE IF NOT EXISTS public.course_documents (
  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  subject_id TEXT NOT NULL,
  subject_label TEXT NOT NULL,
  name TEXT NOT NULL,
  chapter TEXT NOT NULL DEFAULT '',
  material_type TEXT NOT NULL DEFAULT 'course_material',
  content_text TEXT NOT NULL,
  page_count INTEGER NOT NULL DEFAULT 0,
  created_at TIMESTAMPTZ NOT NULL DEFAULT NOW()
);

CREATE INDEX IF NOT EXISTS course_documents_subject_created_idx
  ON public.course_documents (subject_id, created_at DESC);
