-- UNI GENIUS private cloud course knowledge
-- Run once in the Supabase SQL Editor. Keep the service-role key server-side only.
create table if not exists public.course_documents (
  id bigint generated by default as identity primary key,
  subject_id text not null,
  subject_label text not null,
  name text not null,
  chapter text not null default '',
  material_type text not null default 'course_material',
  content_text text not null,
  page_count integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists course_documents_subject_created_idx
  on public.course_documents (subject_id, created_at desc);

alter table public.course_documents enable row level security;

-- No anon/authenticated policies are created. Only the server's service-role
-- credential can access this table; never expose that credential in the browser.
